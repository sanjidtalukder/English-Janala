-- Never use a Supabase secret/service-role key in the browser or this app's .env.

create table if not exists public.word_progress (
    user_id uuid not null references auth.users(id) on delete cascade,
    word_id text not null,
    lesson_no integer not null check (lesson_no between 1 and 100),
    completed_at timestamptz not null default now(),
    review_due_at timestamptz not null default (now() + interval '1 day'),
    last_reviewed_at timestamptz,
    review_stage integer not null default 0 check (review_stage between 0 and 4),
    quiz_correct integer not null default 0 check (quiz_correct >= 0),
    quiz_attempts integer not null default 0 check (quiz_attempts >= 0),
    primary key (user_id, word_id)
);

create index if not exists word_progress_due_idx on public.word_progress (user_id, review_due_at);
create index if not exists word_progress_lesson_idx on public.word_progress (user_id, lesson_no);

create table if not exists public.study_activity (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    activity_date date not null default (timezone('utc', now())::date),
    event_type text not null check (event_type in ('word_completed', 'quiz_attempt')),
    correct boolean,
    created_at timestamptz not null default now(),
    constraint study_activity_correct_for_quiz check (
        (event_type = 'quiz_attempt' and correct is not null)
        or (event_type = 'word_completed' and correct is null)
    )
);

create index if not exists study_activity_user_day_idx on public.study_activity (user_id, activity_date desc);

create table if not exists public.user_settings (
    user_id uuid primary key references auth.users(id) on delete cascade,
    daily_goal integer not null default 5 check (daily_goal between 1 and 100),
    updated_at timestamptz not null default now()
);

create table if not exists public.saved_words (
    user_id uuid not null references auth.users(id) on delete cascade,
    word_id text not null,
    topic text not null default 'My words',
    word_data jsonb not null,
    created_at timestamptz not null default now(),
    primary key (user_id, word_id)
);
create index if not exists saved_words_user_created_idx on public.saved_words (user_id, created_at desc);

alter table public.word_progress enable row level security;
alter table public.study_activity enable row level security;
alter table public.user_settings enable row level security;
alter table public.saved_words enable row level security;

drop policy if exists "Users read own word progress" on public.word_progress;
create policy "Users read own word progress" on public.word_progress
    for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists "Users add own word progress" on public.word_progress;
create policy "Users add own word progress" on public.word_progress
    for insert to authenticated with check ((select auth.uid()) = user_id);
drop policy if exists "Users update own word progress" on public.word_progress;
create policy "Users update own word progress" on public.word_progress
    for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);

drop policy if exists "Users read own study activity" on public.study_activity;
create policy "Users read own study activity" on public.study_activity
    for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists "Users add own study activity" on public.study_activity;
create policy "Users add own study activity" on public.study_activity
    for insert to authenticated with check ((select auth.uid()) = user_id);

drop policy if exists "Users read own settings" on public.user_settings;
create policy "Users read own settings" on public.user_settings
    for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists "Users add own settings" on public.user_settings;
create policy "Users add own settings" on public.user_settings
    for insert to authenticated with check ((select auth.uid()) = user_id);
drop policy if exists "Users update own settings" on public.user_settings;
create policy "Users update own settings" on public.user_settings
    for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);

grant select, insert, update on public.word_progress to authenticated;
grant select, insert on public.study_activity to authenticated;
grant select, insert, update on public.user_settings to authenticated;
drop policy if exists "Users read own saved words" on public.saved_words;
create policy "Users read own saved words" on public.saved_words
    for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists "Users add own saved words" on public.saved_words;
create policy "Users add own saved words" on public.saved_words
    for insert to authenticated with check ((select auth.uid()) = user_id);
drop policy if exists "Users update own saved words" on public.saved_words;
create policy "Users update own saved words" on public.saved_words
    for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
drop policy if exists "Users delete own saved words" on public.saved_words;
create policy "Users delete own saved words" on public.saved_words
    for delete to authenticated using ((select auth.uid()) = user_id);
grant select, insert, update, delete on public.saved_words to authenticated;
grant usage, select on sequence public.study_activity_id_seq to authenticated;
